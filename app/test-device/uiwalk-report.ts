// T5: ui-map.json (test-device/uiwalk.ts) → ui-map.md (a tree per view, the keys' layers per view) and checks.md (every
// failed check of the walk: Back, ×, console errors, overflow, tap targets, names, slow transitions).
//   node test-device/uiwalk-report.ts [--out ../tests/ui-walk] [--md ../docs/research/t5-ui]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parse } from "yaml";

const argOf = (n: string, d: string): string => {
  const i = process.argv.indexOf(`--${n}`);
  return i > 0 && process.argv[i + 1] !== undefined ? (process.argv[i + 1] as string) : d;
};
// the data (ui-map.json, walk-*.json, shots/) and the two pages it writes live apart: the data in tests/ui-walk, the pages in docs
const OUT = resolve(argOf("out", "../tests/ui-walk"));
const MD = resolve(argOf("md", "../docs/research/t5-ui"));

type Action = { k: "tap"; desc: string; nth: number; label: string } | { k: "back" } | { k: "outside" } | { k: "gesture"; name: string };
interface Small { what: string; w: number; h: number }
interface State {
  id: string; key?: string; root: string; path: Action[]; label: string; shot: string; variant?: string; foreign?: string;
  sig: { place: string; view: string | null; sheets: string[]; ov: string[]; layer: string; folded: boolean; unit: boolean; set: string; echo?: string };
  audit?: { w: number; h: number; pageScrollX: boolean; outside: string[]; clipped: string[]; ellipsed: string[]; small: Small[]; line: string; notice: string };
  names?: { role: string; name: string }[];
}
interface Edge { from: string; action: Action; to: string; ms: number | null; line?: string; notice?: string; errors: string[]; back?: string; backMs?: number | null; close?: string; closeHow?: string; note?: string }
interface Profile { made: string; viewport: { w: number; h: number } | null; states: State[]; edges: Edge[] }

const map = JSON.parse(readFileSync(join(OUT, "ui-map.json"), "utf8")) as { profiles: Record<string, Profile> };
const spec = parse(readFileSync(resolve("../spec/keyboard.yaml"), "utf8")) as { keys: { id: string; label?: Record<string, string>; primary?: Record<string, unknown>; shift?: Record<string, unknown>; alpha?: Record<string, unknown> }[] };
const en = (await import("../src/i18n/en.ts")).en as Record<string, string>;
const legend = (l: string | undefined): string => (l === undefined ? "" : l.startsWith("$") ? (en[l.slice(1)] ?? l.slice(1)) : l);
const specAct = (a: Record<string, unknown> | undefined): string => {
  if (!a) return "";
  const [k, v] = Object.entries(a).filter(([k]) => k !== "sample" && k !== "line" && k !== "units")[0] ?? ["", ""];
  return `${k} ${typeof v === "string" ? v : JSON.stringify(v)}`;
};

const act = (a: Action): string =>
  a.k === "tap" ? (a.desc.startsWith("key:") ? `key ${a.desc.slice(4)}` : a.desc.startsWith("row:") ? `row “${a.label}”` : `tap “${a.label || a.desc}”`) : a.k === "gesture" ? `${a.name}` : a.k === "back" ? "Android Back" : "tap outside";
const esc = (s: string): string => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const md: string[] = [];
const checks: string[] = [];
md.push("<!-- SPDX-License-Identifier: GPL-3.0-or-later -->", "# N62 UI map (T5)", "");
md.push("Made by `app/test-device/uiwalk.ts` on emulators (the test build of phase-1), turned into this page by `uiwalk-report.ts`. Each state is named by its id; its screenshot is \`tests/ui-walk/shots/<profile>/<id>.jpg\`, made by each run of the walk and not kept in git; `→` is where an action leads, `Back → pNNN` and `× → pNNN` say where Android Back and the sheet's × lead after the action (checks.md lists the ones that do not lead where docs/05 says), and the time is from the finger's lift to the last change on screen. Typing keys are in the key tables, not the trees.", "");
checks.push("<!-- SPDX-License-Identifier: GPL-3.0-or-later -->", "# T5 walk: every failed check", "", "Generated by `uiwalk-report.ts` from ui-map.json. The findings (F380–F399) in SUMMARY.md and ui-analysis.md are drawn from these lines after a look at each one.", "");

for (const [profile, p] of Object.entries(map.profiles)) {
  const byId = new Map(p.states.map((s) => [s.id, s]));
  const out = new Map<string, Edge[]>();
  for (const e of p.edges) out.set(e.from, [...(out.get(e.from) ?? []), e]);
  const name = (id: string | undefined): string => {
    const s = id ? byId.get(id) : undefined;
    // the per-state screenshots are not in git (.gitignore; owner 2026-11-16): a run makes them under tests/ui-walk/shots/
    return s ? `${s.id} ${esc(s.label)}` : String(id);
  };
  md.push(`## ${profile} (${p.viewport ? `${p.viewport.w} × ${p.viewport.h} CSS px` : "?"}; ${p.states.length} states, ${p.edges.length} edges)`, "");

  // ---- the trees: the spanning tree of the states each root found first, typing edges left out
  const roots = [...new Set(p.states.map((s) => s.root))];
  for (const r of roots) {
    const r0 = p.states.find((s) => s.root === r && s.path.length === 0);
    if (!r0) continue;
    md.push(`### ${r}: ${name(r0.id)}`, "");
    const seen = new Set<string>([r0.id]);
    const walk = (id: string, depth: number): void => {
      const es = (out.get(id) ?? []).filter((e) => e.to !== e.from || e.action.k !== "tap" || !e.action.desc.startsWith("key:"));
      for (const e of es) {
        if (e.to === e.from && !e.notice && e.action.k === "tap" && e.action.desc.startsWith("key:")) continue;
        const to = byId.get(e.to);
        const first = !seen.has(e.to) && to !== undefined && to.root === r && !to.variant && !to.foreign;
        const flags: string[] = [];
        if (e.to === e.from) flags.push(e.notice ? `stays · notice “${esc(e.notice)}”` : e.line ? `stays · line ${esc(e.line).slice(0, 40)}` : "stays");
        if (e.back) flags.push(`Back → ${e.back}`);
        if (e.close) flags.push(`× → ${e.close}`);
        if (e.ms !== null) flags.push(`${e.ms} ms`);
        if (e.errors.length) flags.push(`⚠ ${e.errors.length} console error(s)`);
        if (e.note) flags.push(e.note);
        const target = e.to === e.from ? "" : ` → ${name(e.to)}${to?.variant ? " (a setting changed)" : ""}`;
        md.push(`${"  ".repeat(depth)}- ${esc(act(e.action))}${target}${flags.length ? ` · ${flags.join(" · ")}` : ""}`);
        if (first) {
          seen.add(e.to);
          walk(e.to, depth + 1);
        }
      }
    };
    walk(r0.id, 0);
    md.push("");
  }

  // ---- the keys per view: tap, Shift + key, Alpha + key, flick up, flick down
  md.push(`### ${profile}: the keys in each view`, "");
  for (const r of roots) {
    const r0 = p.states.find((s) => s.root === r && s.path.length === 0);
    if (!r0) continue;
    const es = out.get(r0.id) ?? [];
    if (!es.some((e) => e.action.k === "tap" && e.action.desc.startsWith("key:d"))) continue;
    const layerState = (k: string): string | undefined => es.find((e) => e.action.k === "tap" && e.action.desc === `key:${k}`)?.to;
    const sh = layerState("shift");
    const al = layerState("alpha");
    const outcome = (from: string | undefined, desc: string): string => {
      if (!from) return "";
      const e = (out.get(from) ?? []).find((x) => (x.action.k === "tap" && x.action.desc === desc) || (x.action.k === "gesture" && x.action.name === desc));
      if (!e) return "";
      const to = byId.get(e.to);
      if (e.to !== from && to) return to.variant ? `setting → ${e.to}` : `→ ${e.to} ${to.sig.sheets.at(-1)?.replace(/^[^:]*:/, "") ?? to.label.replace(/^\S+ ?/, "")}`.trim();
      if (e.line) return `\`${e.line.slice(0, 28)}\``;
      if (e.notice) return `“${e.notice.slice(0, 28)}”`;
      return "·";
    };
    const head = ["key", "spec tap", "tap", "Shift + key", "Alpha + key", "flick ↑ (the Shift layer)", "flick ↓ (the Alpha layer)"];
    const table: string[][] = [];
    for (const k of spec.keys) {
      const d = `key:${k.id}`;
      table.push([
        `${k.id} (${legend(k.label?.["primary"])})`,
        esc(specAct(k.primary)),
        esc(outcome(r0.id, d)),
        esc(outcome(sh, d)),
        esc(outcome(al, d)),
        esc(outcome(r0.id, `flick-up:${k.id}`)),
        esc(outcome(r0.id, `flick-down:${k.id}`)),
      ]);
    }
    // a column the walk did not fill for this root (no flicks here, or the layer state was not expanded) is left out
    const keep = head.map((_, c) => c < 3 || table.some((row) => row[c] !== ""));
    md.push(`#### ${r}`, "", `| ${head.filter((_, c) => keep[c]).join(" | ")} |`, `|${head.filter((_, c) => keep[c]).map(() => "---").join("|")}|`);
    for (const row of table) md.push(`| ${row.filter((_, c) => keep[c]).join(" | ")} |`);
    if (r === "units") md.push("", "In the unit view a key fills the slot (a unit cell, P14), which this table's reader (the entry line's value) does not see. So `·` here means only that the line and the state did not change; the unit pad's faces are in the screenshot of the root state.");
    md.push("", "`·` = nothing changed on screen (a cursor move on an empty line, or a dead key); `→ pNNN` = a new state; a code span is what the line holds after the key.", "");
  }

  // ---- speed: the fewest actions from each root's resting state to every state it reaches (a flick or a gesture is one)
  md.push(`### ${profile}: actions to reach each state from its root`, "", "| root | state | actions | the shortest way |", "|---|---|---|---|");
  for (const r of roots) {
    const r0 = p.states.find((s) => s.root === r && s.path.length === 0);
    if (!r0) continue;
    const dist = new Map<string, { n: number; via: string[] }>([[r0.id, { n: 0, via: [] }]]);
    const q = [r0.id];
    while (q.length) {
      const id = q.shift() as string;
      const d = dist.get(id) as { n: number; via: string[] };
      for (const e of out.get(id) ?? []) {
        if (dist.has(e.to) || e.action.k === "back") continue;
        dist.set(e.to, { n: d.n + 1, via: [...d.via, act(e.action)] });
        q.push(e.to);
      }
    }
    for (const [id, d] of [...dist].sort((a, b) => a[1].n - b[1].n)) {
      const s = byId.get(id);
      if (!s || d.n === 0 || s.foreign) continue;
      md.push(`| ${r} | ${name(id)} | ${d.n} | ${esc(d.via.join(", "))} |`);
    }
  }
  md.push("");

  // ---- checks
  checks.push(`## ${profile}`, "");
  const back: string[] = [];
  const close: string[] = [];
  const errs: string[] = [];
  const slow: string[] = [];
  // What Back and × should reach (docs/05 3.1, 3.4): Back undoes the top layer, so after an action that stacked a layer on
  // `from` it is `from`, and after one that replaced `from`'s sheet by another (a status control while a sheet is open) it
  // is the place under both; × closes the whole sheet, so it is the place with no sheet open.
  const plain = (x: State["sig"], sheets: string[]): string => JSON.stringify({ ...x, sheets, ov: x.ov.filter((o) => o !== "find-preview"), echo: undefined });
  const under = (x: State): string | undefined => p.states.find((o) => o.root === x.root && !o.variant && plain(o.sig, o.sig.sheets) === plain(x.sig, []))?.id;
  const expectBack = (f: State, t: State): string | undefined => {
    const fs = f.sig.sheets, ts = t.sig.sheets;
    const top = (a: string[]): string => a[a.length - 1] ?? "";
    if (ts.length > fs.length && fs.every((m, i) => ts[i] === m)) return f.id; // a sheet on top
    // a level on top: the title's path grows (a deep title keeps its last three levels, so match on the last one)
    const last = top(fs).split(" › ").at(-1) ?? "";
    if (fs.length > 0 && ts.length === fs.length && (top(ts).startsWith(`${top(fs)} › `) || top(ts).includes(`${last} › `))) return f.id;
    if (fs.length > 0 && JSON.stringify(ts) === JSON.stringify(fs)) return undefined; // Shift or Alpha inside a sheet: not checked
    if (fs.length > 0 && ts.length > 0) return under(f); // a sheet replaced by another
    return f.id; // a layer or an overlay on a place with no sheet
  };
  for (const e of p.edges) {
    const where = `${e.from} ${esc(byId.get(e.from)?.label ?? "")} · ${esc(act(e.action))} → ${e.to}`;
    const f = byId.get(e.from), t = byId.get(e.to);
    const wantBack = f && t ? expectBack(f, t) : e.from;
    const wantClose = t ? under(t) : undefined;
    // a sheet opened over a picked row or an armed Shift/Alpha drops them (R147), so Back may land on the plain view too
    const plainView = f && t && (f.sig.layer !== "" || f.sig.ov.includes("row-actions")) && t.sig.sheets.length > 0 ? p.states.find((o) => o.root === f.root && !o.variant && o.path.length === 0)?.id : undefined;
    if (e.back && wantBack !== undefined && e.back !== wantBack && e.back !== plainView && !(t?.sig.ov.includes("tips") ?? false)) back.push(`- ${where}: Back → ${name(e.back)}; expected ${name(wantBack)}`);
    if (e.close && wantClose && e.close !== wantClose) close.push(`- ${where}: × (${e.closeHow}) → ${name(e.close)}; expected ${name(wantClose)}`);
    if (e.errors.length) errs.push(`- ${where}: ${e.errors.map(esc).join(" / ")}`);
    // only a key or a gesture is timed cleanly: the app acts on its pointerup. A control that acts on click gets CDP's click
    // synthesis on top (about 250 ms here; real input gave 26-266 ms, ui-analysis.md), and Back gets adb's latency (about 1 s).
    const clean = (e.action.k === "tap" && e.action.desc.startsWith("key:")) || e.action.k === "gesture";
    if (clean && e.ms !== null && e.ms > 300) slow.push(`- ${where}: ${e.ms} ms`);
  }
  checks.push(`### Back does not return (${back.length})`, "", ...back, "", `### × does not return (${close.length})`, "", ...close, "", `### Console errors (${errs.length})`, "", ...errs, "", `### Transitions over 300 ms (${slow.length}; keys and gestures only, the clean timings)`, "", ...slow, "");
  const ms = p.edges.filter((e) => (e.action.k === "tap" && e.action.desc.startsWith("key:")) || e.action.k === "gesture").map((e) => e.ms).filter((m): m is number => m !== null).sort((a, b) => a - b);
  if (ms.length) checks.push(`Transition times of keys and gestures (the lift to the last change on screen; the emulator shared the CPU with three others): n ${ms.length}, median ${ms[Math.floor(ms.length / 2)]} ms, p90 ${ms[Math.floor(ms.length * 0.9)]} ms, max ${ms.at(-1)} ms.`, "");
  const lay: string[] = [];
  const small = new Map<string, { n: number; w: number; h: number; states: Set<string>; eg: string }>();
  const names = new Map<string, Set<string>>();
  const allNames = new Set<string>();
  for (const s of p.states) {
    const a = s.audit;
    if (!a) continue;
    if (a.pageScrollX) lay.push(`- ${name(s.id)}: the page scrolls sideways`);
    for (const o of a.outside) lay.push(`- ${name(s.id)}: outside the screen: ${esc(o)}`);
    // the folded keypad (results mode, R53) is hidden in its 44 px slice on purpose
    for (const c of a.clipped) if (!(s.sig.folded && c.startsWith("#keys "))) lay.push(`- ${name(s.id)}: clipped: ${esc(c)}`);
    for (const t of a.small) {
      // one line per kind of control (a key, a chip, a sheet row, a cell), with one example's label
      const k = t.what.replace(/"[^"]*"|\[[^\]]*\]/g, "").trim() || t.what;
      const v = small.get(k) ?? { n: 0, w: t.w, h: t.h, states: new Set<string>(), eg: t.what };
      v.n++; v.w = Math.min(v.w, t.w); v.h = Math.min(v.h, t.h); v.states.add(s.id);
      small.set(k, v);
    }
    for (const n of s.names ?? []) {
      const nm = n.name.trim();
      const bad = nm === "" ? "no name" : !/[\p{L}\p{N}]/u.test(nm) ? "symbols only" : /^[A-Z]{2,4}$/.test(nm) || /^[0-9]{2,}$/.test(nm) ? "a bare abbreviation or number" : "";
      allNames.add(`${n.role} “${nm}”`);
      if (bad) names.set(`${n.role} “${n.name}” (${bad})`, (names.get(`${n.role} “${n.name}” (${bad})`) ?? new Set()).add(s.id));
    }
  }
  checks.push(`### Overflow and clipping (${lay.length})`, "", ...[...new Set(lay)].slice(0, 300), "");
  checks.push(`### Tap targets under 48 × 48 dp (${small.size} kinds)`, "", "| control | e.g. | smallest w × h | states |", "|---|---|---|---|");
  for (const [k, v] of [...small].sort((a, b) => b[1].states.size - a[1].states.size)) checks.push(`| ${esc(k)} | ${esc(v.eg)} | ${v.w} × ${v.h} | ${v.states.size} |`);
  checks.push("", `### Names a screen reader gets that do not say what the control is (${names.size})`, "");
  for (const [k, v] of names) checks.push(`- ${esc(k)}: ${[...v].slice(0, 8).join(", ")}${v.size > 8 ? ` and ${v.size - 8} more` : ""}`);
  checks.push("", `### Every control's name, once (${allNames.size})`, "", [...allNames].sort().map(esc).join(" · "), "");
  const walkFile = join(OUT, `walk-${profile}.json`);
  if (existsSync(walkFile)) {
    const w = JSON.parse(readFileSync(walkFile, "utf8")) as { from: string; action: string; expect: string; got: string; ok: boolean }[];
    const bad = w.filter((x) => !x.ok);
    checks.push(`### Walk (replay of the map): ${w.length - bad.length}/${w.length} edges as mapped`, "", ...bad.map((x) => `- ${x.from} · ${esc(x.action)}: expected ${x.expect}, got ${esc(x.got)}`), "");
  }
}

writeFileSync(join(MD, "ui-map.md"), md.join("\n") + "\n");
writeFileSync(join(MD, "checks.md"), checks.join("\n") + "\n");
console.log(`wrote ${join(MD, "ui-map.md")} and checks.md`);
